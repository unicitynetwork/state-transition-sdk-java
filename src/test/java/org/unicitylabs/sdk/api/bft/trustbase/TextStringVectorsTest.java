package org.unicitylabs.sdk.api.bft.trustbase;

import static org.junit.jupiter.api.Assertions.assertArrayEquals;
import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;

import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import java.io.IOException;
import java.io.InputStream;
import org.junit.jupiter.api.Test;
import org.unicitylabs.sdk.api.bft.UnicitySeal;
import org.unicitylabs.sdk.api.bft.verification.SealVerificationSession;
import org.unicitylabs.sdk.util.HexConverter;
import org.unicitylabs.sdk.util.verification.VerificationStatus;

/**
 * The cross-SDK CBOR text-string vectors (member ids and witness keys), generated by Go at
 * bft-go-base dbf94198 and shared with the JS and Rust SDKs: a text string decodes byte for byte, a
 * leading U+FEFF is part of the string, invalid UTF-8 is refused, and ids that differ only by a
 * leading U+FEFF are different members whose signatures each count.
 */
class TextStringVectorsTest {

  private static final JsonNode VECTORS = load();

  private static JsonNode load() {
    try (InputStream in = TextStringVectorsTest.class
        .getResourceAsStream("/vectors/text-string/vectors.json")) {
      return new ObjectMapper().readTree(in);
    } catch (IOException e) {
      throw new IllegalStateException(e);
    }
  }

  private static byte[] hex(JsonNode node) {
    return HexConverter.decode(node.asText());
  }

  @Test
  void theCommitteeIsGenesisWithTheBomTwinAsAMemberOfItsOwn() {
    JsonNode committee = VECTORS.get("committee");
    TrustBaseEntry entry = TrustBaseEntry.decode(hex(committee.get("hex")));
    assertEquals(committee.get("entryId").asText(), HexConverter.encode(entry.entryId()));
    assertEquals(3, entry.getMembers().size());
    int i = 0;
    for (JsonNode id : committee.get("memberIdsHex")) {
      assertArrayEquals(hex(id),
          entry.getMembers().get(i++).getNodeId().getBytes(java.nio.charset.StandardCharsets.UTF_8));
    }
  }

  @Test
  void everyDecodeVectorHasTheGoVerdict() {
    int seen = 0;
    for (JsonNode vector : VECTORS.get("decode")) {
      String name = vector.get("name").asText();
      byte[] bytes = hex(vector.get("hex"));
      if (vector.get("valid").asBoolean()) {
        TrustBaseEntry entry = TrustBaseEntry.decode(bytes);
        if (vector.get("reencodesIdentically").asBoolean()) {
          assertArrayEquals(bytes, entry.encode(), name);
        }
      } else {
        assertEquals("encoding", vector.get("errorClass").asText(), name);
        assertThrows(TrustBaseEncodingException.class, () -> TrustBaseEntry.decode(bytes), name);
      }
      seen++;
    }
    assertTrue(seen >= 2, "both the valid and the invalid-UTF-8 vector are there");
  }

  @Test
  void aQuorumThatCountsTheBomTwinAuthenticatesAndTwoOfThreeDoesNot() {
    TrustBaseEntry committee = TrustBaseEntry.decode(hex(VECTORS.get("committee").get("hex")));
    TrustBaseHistory history = TrustBaseHistory.create(committee.entryId());
    history.append(committee);
    SealVerificationSession session = SealVerificationSession.create(history);
    int seen = 0;
    for (JsonNode vector : VECTORS.get("seals")) {
      String name = vector.get("name").asText();
      UnicitySeal seal = UnicitySeal.fromCbor(hex(vector.get("hex")));
      VerificationStatus status = session.authenticate(seal).getStatus();
      assertEquals(vector.get("valid").asBoolean() ? VerificationStatus.OK : VerificationStatus.FAIL,
          status, name);
      seen++;
    }
    assertEquals(2, seen);
  }
}
