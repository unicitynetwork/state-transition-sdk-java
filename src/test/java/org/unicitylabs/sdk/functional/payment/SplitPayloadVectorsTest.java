package org.unicitylabs.sdk.functional.payment;

import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.Test;
import org.unicitylabs.sdk.crypto.secp256k1.SigningService;
import org.unicitylabs.sdk.payment.PaymentData;
import org.unicitylabs.sdk.payment.PaymentDataDeserializer;
import org.unicitylabs.sdk.payment.SplitAllocationProof;
import org.unicitylabs.sdk.payment.SplitMintJustification;
import org.unicitylabs.sdk.payment.SplitResult;
import org.unicitylabs.sdk.payment.SplitToken;
import org.unicitylabs.sdk.payment.SplitTokenRequest;
import org.unicitylabs.sdk.payment.TokenSplit;
import org.unicitylabs.sdk.payment.asset.Asset;
import org.unicitylabs.sdk.payment.asset.AssetId;
import org.unicitylabs.sdk.payment.asset.PaymentAssetCollection;
import org.unicitylabs.sdk.predicate.EncodedPredicate;
import org.unicitylabs.sdk.predicate.builtin.SignaturePredicate;
import org.unicitylabs.sdk.transaction.StateMask;
import org.unicitylabs.sdk.transaction.Token;
import org.unicitylabs.sdk.transaction.TokenId;
import org.unicitylabs.sdk.transaction.TokenSalt;
import org.unicitylabs.sdk.util.HexConverter;

import java.io.InputStream;
import java.math.BigInteger;
import java.util.ArrayList;
import java.util.List;
import java.util.function.Function;

/**
 * Byte-for-byte check against the cross-SDK split payload vectors (generated by the JS SDK,
 * vendored from Rust main; see the README next to the JSON).
 */
public class SplitPayloadVectorsTest {

  private static final String RESOURCE =
          "/org/unicitylabs/sdk/payment/split-payload/split_payload.json";

  private static byte[] unhex(JsonNode n) {
    return HexConverter.decode(n.asText());
  }

  private static PaymentAssetCollection assetsOf(JsonNode array) {
    List<Asset> assets = new ArrayList<>();
    for (JsonNode a : array) {
      assets.add(new Asset(new AssetId(unhex(a.get("id"))), new BigInteger(a.get("value").asText())));
    }
    return PaymentAssetCollection.create(assets.toArray(new Asset[0]));
  }

  @Test
  public void splitMatchesCrossSdkVectorsByteForByte() throws Exception {
    JsonNode root;
    try (InputStream in = SplitPayloadVectorsTest.class.getResourceAsStream(RESOURCE)) {
      Assertions.assertNotNull(in);
      root = new ObjectMapper().readTree(in);
    }
    JsonNode cases = root.get("cases");
    Assertions.assertEquals(2, cases.size());

    for (JsonNode c : cases) {
      String name = c.get("name").asText();
      boolean wrapped = c.get("wrapped").asBoolean();
      PaymentDataDeserializer decoder = wrapped
              ? WrappedPaymentData::decode : TestPaymentData::decode;
      Function<PaymentAssetCollection, PaymentData> make = wrapped
              ? WrappedPaymentData::new : TestPaymentData::new;

      Token source = Token.fromCbor(unhex(c.get("sourceToken")));
      Assertions.assertArrayEquals(make.apply(assetsOf(c.get("sourceAssets"))).encode(),
              source.getGenesis().getData().orElseThrow(), name + ": source payload");

      List<SplitTokenRequest> requests = new ArrayList<>();
      for (JsonNode o : c.get("tokens")) {
        byte[] key = new byte[32];
        key[31] = (byte) o.get("recipientKey").asInt();
        requests.add(SplitTokenRequest.create(
                SignaturePredicate.create(new SigningService(key).getPublicKey()),
                make.apply(assetsOf(o.get("assets"))),
                TokenSalt.fromBytes(unhex(o.get("salt")))));
      }

      SplitResult split = TokenSplit.split(source, decoder, requests,
              StateMask.fromBytes(unhex(c.get("burnStateMask"))),
              c.get("burnExpiresAt").asLong());

      Assertions.assertArrayEquals(unhex(c.get("burnTransaction")),
              split.getBurnTransaction().toCbor(), name + ": burn transaction");
      Assertions.assertArrayEquals(unhex(c.get("manifest")),
              split.getBurnTransaction().getData().orElseThrow(), name + ": manifest");

      Assertions.assertEquals(c.get("tokens").size(), split.getTokens().size());
      for (int i = 0; i < split.getTokens().size(); i++) {
        SplitToken out = split.getTokens().get(i);
        JsonNode expected = c.get("tokens").get(i);

        byte[] payload = out.getPaymentData().encode();
        Assertions.assertArrayEquals(unhex(expected.get("payload")), payload,
                name + ": payload");
        TokenId tokenId = TokenId.fromSalt(out.getNetworkId(), out.getSalt());
        Assertions.assertArrayEquals(unhex(expected.get("tokenId")), tokenId.getBytes(),
                name + ": token id");
        Assertions.assertArrayEquals(unhex(expected.get("commitment")),
                SplitMintJustification.calculateLeafData(source,
                        EncodedPredicate.fromPredicate(out.getRecipient()), out.getSalt(),
                        tokenId, payload),
                name + ": commitment");

        JsonNode proofs = expected.get("proofs");
        Assertions.assertEquals(proofs.size(), out.getProofs().size());
        for (int p = 0; p < proofs.size(); p++) {
          SplitAllocationProof proof = out.getProofs().get(p);
          Assertions.assertArrayEquals(unhex(proofs.get(p)), proof.toCbor(),
                  name + ": allocation proof");
        }
      }
    }
  }
}
